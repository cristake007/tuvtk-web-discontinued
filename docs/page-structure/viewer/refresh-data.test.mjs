import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

import { discoverRoutes } from "./refresh-data.mjs";

test("descoperă generic rute top-level și nested necunoscute", () => {
  const routerSource = `
    export const appRoutes = [
      { path: "/functionalitate-complet-noua", element: <FunctionalitateNouaPage /> },
      {
        path: "/modul-viitor",
        element: <AuthenticationGate />,
        children: [
          { path: "instrument", element: <InstrumentNecunoscutPage /> },
        ],
      },
    ];
  `;

  assert.deepEqual(
    discoverRoutes(routerSource).map(({ path, entryComponent }) => ({ path, entryComponent })),
    [
      { path: "/functionalitate-complet-noua", entryComponent: "FunctionalitateNouaPage" },
      { path: "/modul-viitor/instrument", entryComponent: "InstrumentNecunoscutPage" },
    ],
  );
});

test("generatorul nu folosește outputul anterior sau Markdown ca sursă", async () => {
  const source = await readFile(new URL("./refresh-data.mjs", import.meta.url), "utf8");

  assert.doesNotMatch(source, /JSON\.parse\(existingDataSource\)/);
  assert.doesNotMatch(source, /documentedRouteAnalysis|documentedEndpoints|sharedRuntimeReportFile/);
  assert.match(source, /existsSync\(dataFile\) \? readFile\(dataFile, "utf8"\) : ""/);
});

test("artefactul conține numai rute generate din scanare", async () => {
  const data = JSON.parse(await readFile(new URL("./data.json", import.meta.url), "utf8"));

  assert.equal(data.routes.length, data.meta.scan.discoveredRoutes);
  assert.ok(data.routes.every((route) => route.autoGenerated && route.autoScan));
  assert.ok(data.routes.every((route) => route.report === null));
  assert.equal(data.meta.generatedFrom, "codul frontend și backend");
});
